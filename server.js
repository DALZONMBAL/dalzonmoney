const SCHEMA=`
CREATE TABLE IF NOT EXISTS users(
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 account_id TEXT UNIQUE NOT NULL,name TEXT NOT NULL,email TEXT UNIQUE NOT NULL,
 password_hash TEXT NOT NULL,role TEXT NOT NULL DEFAULT 'user' CHECK(role IN('user','admin')),
 status TEXT NOT NULL DEFAULT 'active' CHECK(status IN('active','blocked')),
 created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS wallets(
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT UNIQUE NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 cdf BIGINT NOT NULL DEFAULT 0 CHECK(cdf>=0),
 usd_cents BIGINT NOT NULL DEFAULT 0 CHECK(usd_cents>=0)
);
CREATE TABLE IF NOT EXISTS cards(
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT UNIQUE NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 card_number TEXT UNIQUE NOT NULL,expiry TEXT NOT NULL,
 status TEXT NOT NULL DEFAULT 'active' CHECK(status IN('active','blocked'))
);
CREATE TABLE IF NOT EXISTS transactions(
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 type TEXT NOT NULL,currency TEXT NOT NULL CHECK(currency IN('CDF','USD')),
 amount_cdf BIGINT NOT NULL DEFAULT 0,amount_usd_cents BIGINT NOT NULL DEFAULT 0,
 description TEXT,reference TEXT,created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_users_email ON users(email);
CREATE INDEX IF NOT EXISTS idx_users_account ON users(account_id);
CREATE INDEX IF NOT EXISTS idx_tx_user ON transactions(user_id);
CREATE INDEX IF NOT EXISTS idx_tx_date ON transactions(created_at DESC);
`;

async function q(text,params=[],client=pool){return (await client.query(text,params)).rows}
async function user(id,client=pool){return (await q("SELECT * FROM users WHERE id=$1",[id],client))[0]||null}
async function wallet(id,client=pool){return (await q("SELECT * FROM wallets WHERE user_id=$1",[id],client))[0]||null}
async function card(id,client=pool){return (await q("SELECT * FROM cards WHERE user_id=$1",[id],client))[0]||null}
async function account(id,client=pool){
 const u=await user(id,client); if(!u)return null; const w=await wallet(id,client),c=await card(id,client);
 return {id:Number(u.id),account_id:u.account_id,name:u.name,email:u.email,role:u.role,status:u.status,created_at:u.created_at,
   wallet:{CDF:w?Number(w.cdf):0,USD:w?Number(w.usd_cents)/100:0},
   card:c?{id:Number(c.id),number:c.card_number,expiry:c.expiry,status:c.status}:null};
}
function aid(){return `DLZ-${new Date().getFullYear()}-${crypto.randomInt(100000,1000000)}`}
function cnum(){return [1,2,3,4].map(()=>crypto.randomInt(1000,10000)).join(" ")}
function expiry(){const d=new Date();d.setFullYear(d.getFullYear()+4);return `${String(d.getMonth()+1).padStart(2,"0")}/${String(d.getFullYear()).slice(-2)}`}
function ref(p="DLZ"){return `${p}-${Date.now()}-${crypto.randomBytes(4).toString("hex").toUpperCase()}`}
async function uniqueAccount(c){for(;;){const x=aid();if(!(await q("SELECT 1 FROM users WHERE account_id=$1",[x],c)).length)return x}}
async function uniqueCard(c){for(;;){const x=cnum();if(!(await q("SELECT 1 FROM cards WHERE card_number=$1",[x],c)).length)return x}}
async function tx(fn){const c=await pool.connect();try{await c.query("BEGIN");const r=await fn(c);await c.query("COMMIT");return r}catch(e){await c.query("ROLLBACK");throw e}finally{c.release()}}
function token(u){return jwt.sign({id:Number(u.id),role:u.role,account_id:u.account_id},JWT_SECRET,{expiresIn:"30d"})}
async function auth(req,res,next){
 const h=req.headers.authorization||"";if(!h.startsWith("Bearer "))return res.status(401).json({ok:false,message:"Authentification requise."});
 try{const d=jwt.verify(h.slice(7),JWT_SECRET),u=await user(d.id);if(!u)return res.status(401).json({ok:false,message:"Compte introuvable."});if(u.status!=="active")return res.status(403).json({ok:false,message:"Ce compte est bloqué."});req.user=u;next()}catch(e){res.status(401).json({ok:false,message:"Session invalide ou expirée."})}
}
function admin(req,res,next){if(req.user?.role!=="admin")return res.status(403).json({ok:false,message:"Accès administrateur refusé."});next()}
function name(v){return String(v||"").trim().replace(/\s+/g," ")}
function email(v){return String(v||"").trim().toLowerCase()}
function money(req){
 const currency=String(req.body.currency||"CDF").toUpperCase(),amount=Number(req.body.amount);
 return {currency,amount,amountCdf:currency==="CDF"?Math.round(amount):0,amountUsdCents:currency==="USD"?Math.round(amount*100):0}
}

