app.post("/api/transfer",auth,async(req,res,next)=>{
 const m=money(req),to=String(req.body.recipient||req.body.account_id||req.body.accountId||"").trim().toLowerCase(),d=String(req.body.description||"Transfert DALZON Wallet").trim().slice(0,200);
 if(!to)return res.status(400).json({ok:false,message:"Destinataire requis."});if(!["CDF","USD"].includes(m.currency))return res.status(400).json({ok:false,message:"Devise invalide."});if(!Number.isFinite(m.amount)||m.amount<=0)return res.status(400).json({ok:false,message:"Montant invalide."});
 try{const r=await tx(async c=>{
  const u=(await q("SELECT * FROM users WHERE LOWER(email)=$1 OR LOWER(account_id)=$1 LIMIT 1 FOR UPDATE",[to],c))[0];
  if(!u){const x=new Error("NO_RECIPIENT");x.code="NO_RECIPIENT";throw x}if(Number(u.id)===Number(req.user.id)){const x=new Error("SELF");x.code="SELF";throw x}if(u.status!=="active"){const x=new Error("BLOCKED");x.code="BLOCKED";throw x}
  const sw=await wallet(req.user.id,c),rw=await wallet(u.id,c);if(!sw||!rw){const x=new Error("WALLET");x.code="WALLET";throw x}
  if(m.currency==="CDF"){if(Number(sw.cdf)<m.amountCdf){const x=new Error("FUNDS");x.code="FUNDS";throw x}await q("UPDATE wallets SET cdf=cdf-$1 WHERE user_id=$2",[m.amountCdf,req.user.id],c);await q("UPDATE wallets SET cdf=cdf+$1 WHERE user_id=$2",[m.amountCdf,u.id],c)}
  else{if(Number(sw.usd_cents)<m.amountUsdCents){const x=new Error("FUNDS");x.code="FUNDS";throw x}await q("UPDATE wallets SET usd_cents=usd_cents-$1 WHERE user_id=$2",[m.amountUsdCents,req.user.id],c);await q("UPDATE wallets SET usd_cents=usd_cents+$1 WHERE user_id=$2",[m.amountUsdCents,u.id],c)}
  const rr=ref("TRF");await q("INSERT INTO transactions(user_id,type,currency,amount_cdf,amount_usd_cents,description,reference) VALUES($1,'transfer',$2,$3,$4,$5,$6)",[req.user.id,m.currency,m.amountCdf,m.amountUsdCents,d,rr],c);await q("INSERT INTO transactions(user_id,type,currency,amount_cdf,amount_usd_cents,description,reference) VALUES($1,'receive',$2,$3,$4,$5,$6)",[u.id,m.currency,m.amountCdf,m.amountUsdCents,d,rr],c);return rr
 });res.json({ok:true,message:"Transfert effectué.",reference:r})
 }catch(x){if(x.code==="NO_RECIPIENT")return res.status(404).json({ok:false,message:"Destinataire introuvable."});if(x.code==="SELF")return res.status(400).json({ok:false,message:"Vous ne pouvez pas vous transférer de l'argent à vous-même."});if(x.code==="BLOCKED")return res.status(403).json({ok:false,message:"Le compte destinataire est bloqué."});if(x.code==="FUNDS")return res.status(400).json({ok:false,message:"Solde insuffisant."});next(x)}
});

